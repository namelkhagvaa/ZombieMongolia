#pragma once

#include "Polygon.h"

#include <vector>

// Монгол улсын 21 аймаг ба нийслэл Улаанбаатар: нэр ба хилийн бүдүүвч.
// Хилийн цэгүүд нь (уртраг, өргөрөг). Хөрш аймгууд ижил цэгүүдийг хуваалцдаг тул хил нь яг нийлнэ.
struct Province
{
    const char* name;
    Polygon outline;            // гадна хил
    std::vector<Polygon> holes; // дотор орших өөр засаг захиргааны нэгж (жишээ нь Төв аймаг доторх Улаанбаатар)
};

// Дараалал нь аяны дараалал: хамгийн баруун аймгаас зүүн тийш.
const std::vector<Province>& Provinces();

// (уртраг, өргөрөг) -> хавтгай (зүүн, хойд) координат, градусаар. Өргөрөгөөс хамаарах уртрагийн агшилтыг тооцно.
Vector2 ProjectLonLat(Vector2 lonLat);

// Даалгаврын талбар: аймгийн хилийн хэлбэрийг тоглоомын ертөнцөд буулгана.
// Хилээс хамгийн хол дотоод цэг нь ертөнцийн (0, 0) буюу тоглогчийн эхлэх цэг болж,
// хамгийн алсын орой нь radius зайд очихоор томруулна. Буцаах цэгүүд нь ертөнцийн (x, z).
Shape MakeMissionShape(int provinceIndex, float radius);
