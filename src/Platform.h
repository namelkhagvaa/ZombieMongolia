#pragma once

// Хөтөч (WebAssembly) дээр ажиллахад хэрэгтэй жижиг ялгаанууд.
// Хөтөч дотор үндсэн урсгал frame бүрийн дараа удирдлагыг хөтчид буцааж байж зураг дэлгэцэнд гарна
// (-sASYNCIFY). raylib-ийн WindowShouldClose нь хөтөч дээр үргэлж 16 мс унтдаг тул оронд нь эдгээрийг хэрэглэнэ.

// Цонхыг хаах хүсэлт ирсэн эсэх (хөтөч дээр хэзээ ч үгүй).
bool AppShouldClose();

// EndDrawing-ийн дараа: хөтөч дээр дараагийн requestAnimationFrame хүртэл хүлээнэ; бусад платформд юу ч хийхгүй.
void FrameYield();

// Мэдрэгчтэй дэлгэц (хөтөч): үндсэн оролт нь хуруу эсэх (утас, таблет). Бусад платформд false.
bool WebIsTouchDevice();

// Хөтөч: одоо дэлгэцэд хүрч буй хуруунууд (дэлгэцийн пикселээр, GetScreenWidth/Height-тэй ижил).
// raylib-ийн вэб давхарга өргөсөн хурууг жагсаалтад үлдээдэг тул хөтчийн event.touches-ийг шууд уншина.
// capacity = 0 бол зөвхөн тоог буцаана. Бусад платформд 0.
int WebReadTouches(float* xy, int* ids, int capacity);

// Хөтөч: хуудасны ачааллын дэлгэцийг (web/shell.html) нууна; тоглоомын эхлэлийн дэлгэц түүнийг орлоно.
void WebHideLoader();

// Хөтөч: эхэнд нэг удаа ачаалсан файлуудыг (загвар, текстур, дуу) хуудасны санах ойгоос чөлөөлнө (~70 MB).
// Дараа нь уншигддаг жижиг файлууд (HUD, газрын зургийн икон, дэвсгэр) үлдэнэ. Бусад платформд юу ч хийхгүй.
void WebReleaseLoadedAssets();

// Хөтөч: WebAssembly санах ойн хэмжээ (MB); бусад платформд 0.
int WebHeapMegabytes();

// Хөтөч: эхлэлийн дэлгэц дууссан (тоглоом бэлэн) — хуудас "ТОГЛОХ" товч гаргаж, дарахад бүтэн дэлгэц болгоно.
void WebLoadingFinished();

// Хөтөч: хулганы түгжээ (pointer lock) сүүлд асуухаас хойш алдагдсан бол true (tab солих, ESC г.м.).
// Бусад платформд үргэлж false.
bool WebPointerLockLost();

// Хөтөч: хэрэглэгчээс тоо асууна (prompt цонх). Цуцалсан эсвэл тоо биш бол 0. Бусад платформд 0.
int WebPromptNumber(const char* message);

// Хөтөч (утас): утасны өөрийн гараар бичих. Тоглоомын талбар бүрийн дээр үл үзэгдэх жинхэнэ <input> байрлана:
// хуруу шууд түүн дээр буудаг тул гар бүх хөтөч (iPhone-ий Safari ч) дээр нээгдэнэ, бичсэнийг тоглоомын талбар
// харуулна. Байрлал нь харагдацын координатаар. kind: 0 текст, 1 утасны дугаар, 2 нууц үг. next: гарын Enter-ээр
// шилжих талбарын slot (-1 = илгээх). value-г зөвхөн тухайн <input> идэвхгүй үед хуулна.
void WebFieldPlace(int slot, float x, float y, float width, float height, int kind, int next, const char* value);
void WebFieldsEnd(); // энэ frame-д байрлуулаагүй талбаруудыг нууна (Draw-ийн төгсгөлд)
// Идэвхтэй (гар нээлттэй) талбарын slot, -1 = алга. buffer-т утгыг нь хуулна; enter = сүүлийн талбарт Enter дарсан.
int WebFieldPoll(char* buffer, int capacity, bool& enter);
void WebFieldBlur(); // гарыг хаана
// Хөтөч: утасны гар нээгдсэн үед дэлгэцийн харагдах хэсэг (0..1, дээрээс). Бусад платформд 1.
float WebVisibleFraction();

// Видео картын нэр (OpenGL драйвер; хөтөч дээр WebGL-ийн бодит нэр, мэдэгдэхгүй бол хоосон) ба процессорын
// логик цөмийн тоо: графикийг төхөөрөмжид тааруулж сонгоход (InitWindow-ийн дараа дуудна).
const char* GpuName();
int CpuCores();

// Хадгалалтын файлыг хөтчийн localStorage-тэй тааруулна (бусад платформд юу ч хийхгүй).
void WebRestoreFile(const char* path); // localStorage -> файл (уншихаас өмнө)
void WebPersistFile(const char* path); // файл -> localStorage (бичсэний дараа)
